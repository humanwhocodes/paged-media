export const MARGIN_BOX_NAMES = [
	"top-left-corner",
	"top-left",
	"top-center",
	"top-right",
	"top-right-corner",
	"left-top",
	"left-middle",
	"left-bottom",
	"right-top",
	"right-middle",
	"right-bottom",
	"bottom-left-corner",
	"bottom-left",
	"bottom-center",
	"bottom-right",
	"bottom-right-corner",
] as const;

export type MarginBoxName = (typeof MARGIN_BOX_NAMES)[number];

export interface PageRule {
	selectors: PageSelector[];
	declarations: Declaration[];
	marginBoxes: Map<MarginBoxName, Declaration[]>;
	footnote: Declaration[];
	/** Source order. */
	order: number;
}

export interface PageContext {
	/** The page name (from the `page` property), if any. */
	name?: string;
	/** 1-based index of the page in the document. */
	index: number;
	/** 1-based index of the page within its page group (run of same-named pages). */
	groupIndex: number;
	/** Whether this is the first page of the document. */
	first: boolean;
	/** Whether this is a blank page generated by a forced break. */
	blank: boolean;
	side: "left" | "right";
}

export interface Margins {
	top: number;
	right: number;
	bottom: number;
	left: number;
}

export interface PageStyle {
	size: PageSize;
	orientation?: string;
	margins: Margins;
	marks: { crop: boolean; cross: boolean };
	bleed: number;
	counterReset: [string, number][];
	counterIncrement: [string, number][];
	/** Remaining page-box declarations (background, border, padding, ...). */
	declarations: Declaration[];
	marginBoxes: Map<MarginBoxName, Declaration[]>;
	footnote: Declaration[];
}

export interface PageStyleOptions {
	defaultSize: PageSize;
	defaultMargin: number;
	fontSize: number;
	/**
	 * Resolves a custom property referenced with `var()` in a page
	 * declaration (e.g. `size: var(--page-width) var(--page-height)`).
	 * Returns undefined when the property is not defined.
	 */
	resolveVariable?: (name: string) => string | undefined;
}

//-----------------------------------------------------------------------------
// Collection
//-----------------------------------------------------------------------------

const MARGIN_BOX_SET = new Set<string>(MARGIN_BOX_NAMES);

/**
 * Converts a parsed @page at-rule into a page rule.
 * @param rule The at-rule.
 * @param order The source order.
 * @returns The page rule, or undefined if the selector is invalid.
 */
export function createPageRule(
	rule: AtRule,
	order: number,
): PageRule | undefined {
	if (rule.type !== "at" || rule.name.toLowerCase() !== "page") {
		throw new TypeError("Expected an @page rule.");
	}

	const selectors = parsePageSelectors(rule.prelude);

	if (!selectors) {
		return undefined;
	}

	const marginBoxes = new Map<MarginBoxName, Declaration[]>();
	const footnote: Declaration[] = [];

	for (const nested of rule.rules ?? []) {
		if (nested.type !== "at") {
			continue;
		}

		const name = nested.name.toLowerCase();

		if (MARGIN_BOX_SET.has(name)) {
			const boxName = name as MarginBoxName;
			const existing = marginBoxes.get(boxName) ?? [];
			existing.push(...(nested.declarations ?? []));
			marginBoxes.set(boxName, existing);
		} else if (name === "footnote") {
			footnote.push(...(nested.declarations ?? []));
		}
	}

	return {
		selectors,
		declarations: rule.declarations ?? [],
		marginBoxes,
		footnote,
		order,
	};
}

